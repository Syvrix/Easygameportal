/**
 * Send a command to a running server's console (RCON or tmux send-keys).
 */
async function sendConsoleCommand(server, command, send) {
  if (!command) return send({ type: "error", text: "No command provided" });
  try {
    send({ type: "terminal", stream: "cmd", text: `./${server.cmd} send "${command}"` });
    const dir = serverDir(server);
    await spawnAndStream("bash", [lgsmScript(server), "send", command], dir, send);
    send({ type: "done", action: "console", success: true });
  } catch (err) {
    send({ type: "done", action: "console", success: false, error: err.message });
  }
}

